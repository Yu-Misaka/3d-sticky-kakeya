#!/usr/bin/env python3
"""Regenerate the Core comparison evidence and two TikZ figures from this tree.

Run from any directory with Python 3 and Graphviz installed. The Lean graph
comes only from blueprint's compiled-reference report; expert edges only
provide the comparison graph and the shared layout.
"""

from __future__ import annotations

import hashlib
import json
import subprocess
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "blueprint/scripts"))

import atlas
import check


def read_json(path: Path) -> dict:
    return json.loads(path.read_text())


def node_record(node: dict, registry: dict) -> dict:
    primary = registry.get(node["primary"])
    return {
        "id": node["id"],
        "paper": node["paper"],
        "roadmap_statement": node["statement"],
        "primary": node["primary"],
        "status": node["status"],
        "correspondence": node["remark"],
        "primary_declaration": primary,
        "versions": [
            {
                "name": version["name"],
                "status": version["status"],
                "reached": version["reached"],
                "is_proof": version.get("is_proof"),
                "is_proposition": version.get("is_proposition"),
                "file": registry[version["name"]]["file"],
                "line": version["line"],
            }
            for version in node["versions"]
        ],
    }


LABELS = {
    "W2MW": ("Def. 2.12", "All-scale CWA"),
    "W2L2_13": ("Lemma 2.13", "Inheritance"),
    "W2Sigma": ("Section 6.2", "Critical exponent"),
    "W2D6_1": ("Def. 6.1", "Extremal pair"),
    "W2P6_2": ("Prop. 6.2", "Coarse / fine"),
    "W2P6_3": ("Prop. 6.3", "Lipschitz grains"),
    "W2P6_4": ("Prop. 6.4", "C2 grains"),
    "T5_2": ("WZ1 Thm. 5.2", "General dichotomy"),
    "W2L6_6": ("Lemma 6.6", "Slope on a slab"),
    "W2P6_5": ("Prop. 6.5", "Large slope"),
    "W2L6_7": ("Lemma 6.7", "Small projection"),
    "W2Zero": ("Section 6.5", "Contradiction"),
    "W2JetCount": ("Lemma 7.12", "Cinematic assembly"),
    "W2L7_12": ("Lemma 7.12", "One-scale bound"),
    "T7_2": ("WZ2 Thm. 7.13", "Cinematic estimate"),
    "W2P7_1": ("Prop. 7.1", "Projection lower"),
    "W2P6_8": ("Prop. 6.8", "CWA lower bound"),
    "W2T5_2": ("WZ2 Thm. 5.2", "Union estimate"),
}

STYLES = {
    "core": "-{Latex[length=2.2mm]},draw=blue!45!black,line width=.6pt",
    "api": "-{Latex[length=2.2mm]},draw=gray,dashed,line width=.55pt",
    "assembly": "-{Latex[length=2.2mm]},draw=violet!65!black,dash dot,line width=.6pt",
    "compressed": "-{Latex[length=2.2mm]},draw=violet!65!black,dash pattern=on 5pt off 2pt,line width=.6pt",
}


def figures(view: dict, nodes: dict) -> str:
    pairs = sorted({(edge["from"], edge["to"])
                    for layer in view["edge_layers"].values() for edge in layer})
    dot = ["digraph Core {", "rankdir=BT;", "graph [nodesep=.4,ranksep=.55];",
           'node [shape=box,width=1.65,height=.56,fontsize=10,fontname="Helvetica"];']
    for node_id in view["nodes"]:
        label = "\\n".join(LABELS[node_id])
        dot.append(f'{node_id} [label="{label}"];')
    for source, target in pairs:
        dot.append(f"{source} -> {target};")
    dot.append("}")
    layout = json.loads(subprocess.run(
        ["dot", "-Tjson"], input="\n".join(dot), text=True,
        check=True, capture_output=True).stdout)
    objects = {node["_gvid"]: node for node in layout["objects"]}
    splines = {(objects[edge["tail"]]["name"], objects[edge["head"]]["name"]): edge
               for edge in layout["edges"]}

    def point(values: list | tuple) -> str:
        return f"({float(values[0]) * 2.54 / 72:.5f},{float(values[1]) * 2.54 / 72:.5f})"

    result = ["% Generated by core-proof-dag-evidence.py; union layout is shared."]
    for layer, macro in [("roadmap", "CoreRoadmapFigure"), ("lean", "CoreLeanFigure")]:
        result += [f"\\newcommand{{\\{macro}}}{{%",
                   "\\begin{tikzpicture}[x=1cm,y=1cm,font=\\sffamily\\small]"]
        for edge in view["edge_layers"][layer]:
            geometry = splines[(edge["from"], edge["to"])]
            curves = [item["points"] for item in geometry["_draw_"] if item["op"] == "b"]
            for curve in curves:
                path = point(curve[0])
                for index in range(1, len(curve), 3):
                    path += (f" .. controls {point(curve[index])} and "
                             f"{point(curve[index + 1])} .. {point(curve[index + 2])}")
                endpoint = geometry["pos"].split()[0]
                if endpoint.startswith("e,"):
                    path += " -- " + point(endpoint.split(",")[1:])
                result.append(f"\\draw[{STYLES[edge['role']]}] {path};")
        for node in layout["objects"]:
            node_id = node["name"]
            status = nodes[node_id]["status"]
            if status == "unmatched":
                style = "fill=orange!10,draw=orange!65!black,dashed"
            elif status == "unused-interface":
                style = "fill=gray!10,draw=gray,dashed"
            elif status == "used-interface":
                style = "fill=gray!6,draw=gray!70!black"
            else:
                style = "fill=blue!4,draw=blue!50!black"
            label = "\\\\".join(LABELS[node_id])
            position = point(node["pos"].split(","))
            width, height = float(node["width"]) * 2.54, float(node["height"]) * 2.54
            result.append(
                f"\\node[{style},rounded corners=1pt,align=center,inner sep=1pt,"
                f"minimum width={width:.5f}cm,minimum height={height:.5f}cm] "
                f"at {position} {{{label}}};")
        result += ["\\end{tikzpicture}%", "}"]
    return "\n".join(result) + "\n"


def main() -> None:
    expert, mapping = atlas.load_sources()
    report = read_json(ROOT / "blueprint/lean-dependencies.json")
    declarations = read_json(ROOT / "blueprint/lean-declarations.json")
    if report["source_sha256"] != declarations["source_sha256"]:
        raise ValueError("Compiled declaration and dependency fingerprints differ.")
    if report["source_sha256"] != check.source_digest():
        raise ValueError("Lean sources changed since the compiled-reference audit.")
    registry = {entry["name"]: entry for entry in declarations["declarations"]}
    _, _, manuscript_nodes = check.inspect_content()
    full = atlas.make_atlas(report, expert, mapping, manuscript_nodes)
    view = next(view for view in full["views"] if view["id"] == "overview")
    nodes = {node["id"]: node for node in full["nodes"]}
    paths = atlas.AuditedPaths(report)
    c2 = nodes["W2P6_4"]["primary"]
    specific = "Kakeya.Assouad.WZ1WellSeparatedProjectionUnionConclusion"
    specific_path = paths.between(c2, specific)
    if not specific_path:
        raise ValueError("The documented C2-to-separated-projection path is absent.")
    input_files = ["blueprint/expert-atlas.json", "blueprint/atlas-mapping.json",
                   "blueprint/lean-declarations.json", "blueprint/lean-dependencies.json",
                   "blueprint/scripts/atlas.py", "blueprint/scripts/dependencies.py"]
    roadmap_pairs = {(edge["from"], edge["to"])
                     for edge in view["edge_layers"]["roadmap"]}
    lean_pairs = {(edge["from"], edge["to"])
                  for edge in view["edge_layers"]["lean"]}
    evidence = {
        "root": report["root"],
        "source_sha256": report["source_sha256"],
        "extractor_sha256": report["extractor_sha256"],
        "input_fingerprints": {
            filename: hashlib.sha256((ROOT / filename).read_bytes()).hexdigest()
            for filename in input_files
        },
        "counts": {
            "nodes": len(view["nodes"]),
            "roadmap_edges": len(roadmap_pairs),
            "lean_edges": len(lean_pairs),
            "common_pairs": len(roadmap_pairs & lean_pairs),
            "roadmap_classifications": dict(Counter(
                edge["classification"] for edge in view["comparisons"])),
            "lean_comparisons": dict(Counter(
                edge["diff"] for edge in view["edge_layers"]["lean"])),
        },
        "nodes": [node_record(nodes[key], registry) for key in view["nodes"]],
        "roadmap_comparisons": view["comparisons"],
        "lean_edges": view["edge_layers"]["lean"],
        "added_core_pairs": [list(pair) for pair in sorted(lean_pairs - roadmap_pairs)],
        "removed_core_pairs": [list(pair) for pair in sorted(roadmap_pairs - lean_pairs)],
        "c2_specific_projection": {"target": specific, "path": specific_path},
    }
    (HERE / "core-proof-dag-evidence.json").write_text(
        json.dumps(evidence, ensure_ascii=False, indent=2) + "\n")
    (HERE / "core-proof-dag-figures.tex").write_text(figures(view, nodes))
    print(json.dumps(evidence["counts"], ensure_ascii=False))


if __name__ == "__main__":
    main()
